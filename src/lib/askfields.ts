/** 이 항목에서 비어 있는 칸과 질문 */
export function emptyFieldQuestions(entry: Pick<Entry, 'name' | 'fields'>, fields: string[]): { field: string; q: string }[] {
  const n = entry.name.trim() || '이 항목';
  return fields
    .filter((f) => !(entry.fields[f] ?? '').trim())
    .map((f) => ({ field: f, q: (Q[f] ?? `{n}의 「${f}」은(는) 어떤가요?`).replace('{n}', n) }));
}
