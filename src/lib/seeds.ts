const DAY = 86_400_000;
/** 그날의 질문 번호 (날짜가 바뀌면 다음 질문, 같은 날은 같은 질문) */
export function seedOfDay(now: number, kind: SeedKind | '' = '', skip = 0): number {
  const pool = SEEDS.map((s, i) => ({ s, i })).filter(({ s }) => !kind || s.kind === kind);
  const day = Math.floor((now - new Date(now).getTimezoneOffset() * 60_000) / DAY);
  return pool[(((day * 7 + skip) % pool.length) + pool.length) % pool.length].i;
}

/** 수첩 글 가운데 「▸ 질문」으로 시작하는 것 (질문 + 답) */
export const isSeedJot = (text: string) => text.startsWith('▸ ');
export const seedJotText = (q: string, a: string) => `▸ ${q}\n${a.trim()}`;
export function splitSeedJot(text: string): { q: string; a: string } {
  const i = text.indexOf('\n');
  return i < 0 ? { q: text.slice(2), a: '' } : { q: text.slice(2, i), a: text.slice(i + 1).trim() };
}
